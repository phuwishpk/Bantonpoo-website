export function getArticle(slug: string): Article | undefined {
  return articles.find((article) => article.slug === slug);
}

/** เรียงใหม่สุดก่อนเสมอ */
export function getSortedArticles(): Article[] {
  return [...articles].sort((a, b) => b.publishedAt.localeCompare(a.publishedAt));
}

export function getLatestArticles(limit = 3): Article[] {
  return getSortedArticles().slice(0, limit);
}

/** บทความที่เกี่ยวข้อง — หมวดเดียวกันก่อน แล้วค่อยเติมจากบทความใหม่สุด */
export function getRelatedArticles(article: Article, limit = 3): Article[] {
  const sorted = getSortedArticles().filter((candidate) => candidate.slug !== article.slug);
  const sameCategory = sorted.filter((candidate) => candidate.categorySlug === article.categorySlug);
  const rest = sorted.filter((candidate) => candidate.categorySlug !== article.categorySlug);
  return [...sameCategory, ...rest].slice(0, limit);
}
